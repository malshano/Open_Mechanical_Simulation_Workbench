"""Thermal stress: heat conduction followed by a structural analysis with the temperature as a load (one-way).

    1. heat:        rho cp dT/dt = div(k grad T) + q'''   (simwb.solvers.thermal_fem, steady or transient)
    2. structure:   K u = f_mech + f_th,   f_th = integral(B^T D alpha (T - T_ref) dV)     (simwb.solvers.static_fem)
                    sigma = D (eps - alpha (T - T_ref))

One-way coupling: the temperature field does not depend on the deformation (exact for small deformations, where the
change of the heat paths is negligible) and the heat generated by deformation (thermoelastic damping, plastic work)
is ignored. Material constants (k, E, alpha) are temperature independent. The part is stress-free at the reference
temperature T_ref (the temperature at which it was assembled / the supports were fitted).

Boundary conditions are split by kind and the same CAD faces may carry both:
    heat:       fixed_temperature, convection, radiation_convection, natural_convection, heat_flux, heat_load
    structure:  fixed_support, frictionless_support, displacement, force, pressure
    symmetry:   a mirror plane - adiabatic for the heat and "no movement through it" for the structure
A body that is free to expand has (almost) no thermal stress: the stress comes from restraint (supports that stop the
expansion), from temperature gradients that the material cannot follow freely (non-linear through the thickness)
and from bonded parts with different expansion coefficients. Use supports that only stop rigid-body motion (e.g.
frictionless supports on symmetry faces) to see the unrestrained state; a fully fixed support is a stiff restraint.

Transient runs store `n_frames` temperature fields; the stiffness matrix is factorised once and each saved frame is
one back-substitution. The main result (report, fields) is that of the LAST frame; the largest stress over the
whole run, and when it occurs, is reported (thermal shock often peaks in the middle of the transient).

engine="calculix" writes the structural problem as a CalculiX deck (*EXPANSION, *INITIAL CONDITIONS and a nodal
*TEMPERATURE field taken from the built-in heat solution) - still one-way, a plain *STATIC step, not CalculiX's
*COUPLED TEMPERATURE-DISPLACEMENT. A transient run is evaluated at the end time only in that engine.
"""
from __future__ import annotations

import time

import numpy as np

from . import static_fem, thermal_fem

THERMAL_TYPES = ("fixed_temperature", "convection", "radiation_convection", "natural_convection", "heat_flux",
                 "heat_load")
STRUCTURAL_TYPES = ("fixed_support", "frictionless_support", "displacement", "force", "pressure")
SINKS = ("fixed_temperature", "convection", "radiation_convection", "natural_convection")
NEUTRAL = ("free", "adiabatic", "wall")  # (no effect on either solver)


def split_bcs(bcs: list):
    """Split the boundary conditions into (thermal, structural) lists; symmetry goes to both."""
    th, st, unknown = [], [], []
    for bc in bcs:
        k = bc["type"]
        if k in THERMAL_TYPES:
            th.append(bc)
        elif k in STRUCTURAL_TYPES:
            st.append(bc)
        elif k == "symmetry":
            th.append(bc)
            st.append(bc)
        elif k not in NEUTRAL:
            unknown.append(k)
    if unknown:
        raise ValueError("Boundary condition type(s) not supported in a thermal stress study: "
                         + ", ".join(sorted(set(unknown))))
    return th, st


def _gravity(settings):
    g = settings.get("gravity", "off")
    if g is None or (isinstance(g, str) and g.lower() in ("off", "")):
        return None
    if isinstance(g, str):
        return (9.81 * np.array(thermal_fem.AXES[g], float)).tolist()
    return [float(x) for x in g]  # (an acceleration vector [m/s2])


def _num(v, default=None):
    if v is None or v == "":
        return default
    return float(v)


def solve(mesh: dict, body_props: dict, bcs: list, settings: dict | None = None, log=print, engine: str = "builtin",
          workdir=None, on_proc=None, progress=None) -> dict:
    """mesh, body_props, bcs as in static_fem.solve; body_props additionally needs the heat data of each body
    ("k" [W/m/K], "heat_W" [W] optional, "rho_cp" [J/m3/K] or "rho" and "cp" for transient runs) and "alpha" [1/K].
    settings: analysis ("steady" | "transient"), end_time, time_step, T_initial, n_frames (transient), T_ref (stress-free
    temperature, default T_initial or 20 C), T_uniform (a uniform body temperature [C] when no thermal boundary
    condition is given), gravity ("off", "-z", ... or an acceleration vector).

    Returns the result of static_fem.solve (displacement [m], von_mises [Pa], fields, report) and
      "temperature": corner-node temperatures [C] (of the last frame); "heat_report": the full thermal_fem report;
      "frames": for a transient run {"times", "temperature", "displacement", "von_mises"} (one entry per saved frame);
      report["thermal"]: T_min / T_max / T_ref / max_dT and, transient, the peak stress over time."""
    t0 = time.time()
    settings = dict(settings or {})
    th_bcs, st_bcs = split_bcs(bcs)
    transient = str(settings.get("analysis") or "steady").lower() == "transient"
    warns = []

    T_init = _num(settings.get("T_initial"))
    T_ref = _num(settings.get("T_ref"))
    ref_defaulted = T_ref is None
    if ref_defaulted:
        T_ref = T_init if T_init is not None else 20.0

    if not [b for b in st_bcs if b["type"] in ("fixed_support", "frictionless_support", "symmetry", "displacement")]:
        raise ValueError("The part is not supported: add supports that stop rigid-body motion. For a free thermal "
                         "expansion use frictionless supports on faces that stay put (e.g. symmetry planes); a fixed "
                         "support restrains the expansion and creates stress.")

    props = {}
    for bid, bp in body_props.items():
        d = dict(bp)
        if not d.get("rho_cp") and d.get("rho") and d.get("cp"):
            d["rho_cp"] = float(d["rho"]) * float(d["cp"])
        props[bid] = d

    n1 = len(mesh["nodes"])
    heat_rep = None
    frames = None
    sinks = [b for b in th_bcs if b["type"] in SINKS]
    heat_loads = [b for b in th_bcs if b["type"] in ("heat_flux", "heat_load")] or any(
        float(bp.get("heat_W") or 0.0) for bp in props.values())
    if not [b for b in th_bcs if b["type"] != "symmetry"] and not any(
            float(bp.get("heat_W") or 0.0) for bp in props.values()):
        # no heat problem: the whole part is at one temperature
        T_uni = _num(settings.get("T_uniform"), T_init)
        if T_uni is None:
            raise ValueError("No temperature given: add a thermal boundary condition (fixed temperature, convection, "
                             "heat load, ...) or set a uniform part temperature.")
        T = np.full(n1, float(T_uni))
        if transient:
            warns.append("No heat boundary conditions: a transient run has nothing to evolve - uniform temperature "
                         "used.")
        log(f"Uniform temperature {T_uni:g} C (no heat problem)")
    else:
        if not sinks and not transient:
            raise ValueError("The temperature level is undefined: add at least one 'fixed temperature' or "
                             "'convection' boundary condition (otherwise heat has nowhere to go).")
        if not sinks and transient and heat_loads:
            warns.append("There is no cooling boundary (fixed temperature / convection): the part keeps heating up "
                         "for the whole run.")
        trans = None
        if transient:
            trans = {"end_time": float(settings["end_time"]), "dt": _num(settings.get("time_step"), 0.0),
                     "T0": float(T_init if T_init is not None else 20.0),
                     "n_frames": int(settings.get("n_frames") or 21)}
        log("Heat conduction" + (" (transient)" if transient else ""))
        hres = thermal_fem.solve(mesh, props, th_bcs, log=log, transient=trans,
                                 progress=(lambda f, msg: progress(0.5 * f, msg)) if progress else None)
        imb = hres["report"].get("energy_balance", {}).get("imbalance_percent", 0.0)
        if imb > 1.0 or not np.isfinite(hres["T"]).all():
            raise RuntimeError(f"The heat balance does not close ({imb:.0f} % off): the heat has no effective way "
                               "out. Add a fixed temperature or a convection boundary with h > 0.")
        heat_rep = hres["report"]
        T = hres["T"]
        if transient and hres.get("frames"):
            fr = hres["frames"]
            frames = {"times": list(fr["times"]), "T": [np.asarray(x) for x in fr["T"]]}
            T = frames["T"][-1]
        warns.extend(w for w in heat_rep.get("warnings", []) if w not in warns)

    if ref_defaulted:
        warns.append(f"Stress-free reference temperature not set: taken as {T_ref:g} C "
                     + ("(the initial temperature)" if T_init is not None else "(room temperature, the default)")
                     + ". Set T_ref to the temperature at which the part was assembled - thermal stress is "
                       "proportional to T - T_ref.")
    if np.ptp(T) < 1e-9 and abs(T.max() - T_ref) < 1e-9:
        warns.append("The temperature equals the reference temperature everywhere: there is no thermal load.")

    alpha = {bid: bp.get("alpha") for bid, bp in props.items()}
    thermal = {"T_C": T, "T_ref_C": T_ref, "alpha": alpha}
    if frames is not None and len(frames["T"]) > 1:
        thermal["extra_T_C"] = frames["T"][:-1]
    gravity = _gravity(settings)

    if engine == "calculix":
        from . import calculix

        if frames is not None:
            warns.append("CalculiX engine: the structure is solved at the end time only (use the built-in solver "
                         "for the stress history).")
        res = calculix.solve_static(mesh, props, st_bcs, gravity=gravity, log=log, workdir=workdir, on_proc=on_proc,
                                    thermal={k: v for k, v in thermal.items() if k != "extra_T_C"})
        frames_s = None
    else:
        if progress:
            progress(0.5, "Solving for thermal stress and deformation")
        res = static_fem.solve(mesh, props, st_bcs, gravity=gravity, log=log, thermal=thermal)
        frames_s = res.pop("frames", None)

    rep = res["report"]
    dT = T - T_ref
    th = rep.setdefault("thermal", {})
    th.update({"T_min": float(T.min()), "T_max": float(T.max()), "T_ref": float(T_ref),
               "max_dT": float(np.abs(dT).max()), "analysis": "transient" if frames is not None else "steady",
               "one_way_coupling": True})
    if heat_rep is not None:
        th["heat_energy_imbalance_percent"] = heat_rep.get("energy_balance", {}).get("imbalance_percent")
    rep["warnings"] = list(dict.fromkeys(warns + list(rep.get("warnings", []))))
    rep["assumptions"] = list(rep.get("assumptions", [])) + [
        "One-way thermal-structural coupling: the temperature is computed first and applied as a thermal strain; "
        "deformation does not change the heat flow and no heat is generated by straining",
        "Material properties (conductivity, stiffness, expansion) do not depend on temperature"]

    fields = dict(res.get("fields") or {})
    fields["Temperature"] = (np.asarray(T, float), "°C")
    out = {"displacement": res["displacement"], "von_mises": res["von_mises"], "fields": fields, "report": rep,
           "temperature": np.asarray(T, float), "heat_report": heat_rep}

    if frames is not None and frames_s is not None:
        disp = frames_s["displacement"] + [res["displacement"]]
        vm = frames_s["von_mises"] + [res["von_mises"]]
        out["frames"] = {"times": frames["times"], "temperature": frames["T"], "displacement": disp, "von_mises": vm}
        peaks = [float(np.max(v)) for v in vm]
        i = int(np.argmax(peaks))
        th["peak_von_mises_over_time_MPa"] = peaks[i] / 1e6
        th["peak_time_s"] = float(frames["times"][i])
        if i != len(vm) - 1 and peaks[i] > 1.1 * peaks[-1]:
            rep["warnings"].append(
                f"The stress peaks at t = {frames['times'][i]:.4g} s ({peaks[i] / 1e6:.4g} MPa), above the value at "
                f"the end time ({peaks[-1] / 1e6:.4g} MPa): look at the time frames, not only the final state.")
    th["seconds"] = round(time.time() - t0, 2)
    return out
