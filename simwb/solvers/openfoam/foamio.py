"""OpenFOAM ASCII I/O: polyMesh writer for tetrahedral meshes, polyMesh/field readers."""
from __future__ import annotations

import io
import re
from pathlib import Path

import numpy as np

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by Mechanical Simulation Workbench
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
{location}    object      {obj};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

"""


def header(cls: str, obj: str, location: str | None = None) -> str:
    loc = f'    location    "{location}";\n' if location else ""
    return HEADER.format(cls=cls, obj=obj, location=loc)


def sanitize(name: str) -> str:
    s = re.sub(r"[^A-Za-z0-9_]+", "_", name.strip()).strip("_").lower()
    if not s or not s[0].isalpha():
        s = "p_" + s
    return s[:60]


