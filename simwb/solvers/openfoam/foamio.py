_COMMENT = re.compile(r"//.*?$|/\*.*?\*/", re.S | re.M)


def read_text(path) -> str:
    """An OpenFOAM file, also when it was written compressed (writeCompression on: name.gz)."""
    p = Path(path)
    if not p.exists() and p.with_name(p.name + ".gz").exists():
        import gzip

        with gzip.open(p.with_name(p.name + ".gz"), "rt", errors="ignore") as f:
            return f.read()
    return p.read_text(errors="ignore")


def exists(path) -> bool:
    """The file is there, plain or compressed."""
    p = Path(path)
    return p.exists() or p.with_name(p.name + ".gz").exists()


def _strip_header(text: str) -> str:
    text = _COMMENT.sub("", text)
    i = text.find("FoamFile")
    if i >= 0:
        j = text.find("}", i)
        text = text[j + 1:]
    return text


def _read_list_block(text: str, pos: int = 0):
    """Read 'N\n(\n ... \n)' starting at pos; returns (body_string, count, end_pos)."""
    m = re.compile(r"(\d+)\s*\(").search(text, pos)
    n = int(m.group(1))
    start = m.end()
    depth = 1
    i = start
    while depth:
        c = text[i]
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        i += 1
    return text[start:i - 1], n, i


def read_points(path) -> np.ndarray:
    body, n, _ = _read_list_block(_strip_header(read_text(path)))
    arr = np.array(body.replace("(", " ").replace(")", " ").split(), float).reshape(n, 3)
    return arr


def read_labels(path) -> np.ndarray:
    body, n, _ = _read_list_block(_strip_header(read_text(path)))
    return np.array(body.split(), np.int64)


def read_faces(path):
    """Returns list-of-arrays (polygons). Fast path for all-triangle meshes."""
    body, n, _ = _read_list_block(_strip_header(read_text(path)))
    toks = body.replace("(", " ").replace(")", " ").split()
    a = np.array(toks, np.int64)
    if len(a) == 4 * n and (a[::4] == 3).all():
        return a.reshape(n, 4)[:, 1:], None
    faces, i = [], 0
    while i < len(a):
        k = a[i]
        faces.append(a[i + 1:i + 1 + k])
        i += 1 + k
    return None, faces


def read_boundary(path) -> list:
    text = _strip_header(read_text(path))
    out = []
    for m in re.finditer(r"(\w+)\s*\{([^}]*)\}", text):
        body = m.group(2)
        t = re.search(r"\btype\s+(\w+);", body)
        nf = re.search(r"nFaces\s+(\d+);", body)
        sf = re.search(r"startFace\s+(\d+);", body)
        if nf and sf:
            out.append({"name": m.group(1), "type": t.group(1) if t else "patch",
                        "nFaces": int(nf.group(1)), "start": int(sf.group(1))})
    return out


def read_polymesh(mesh_dir) -> dict:
    d = Path(mesh_dir)
    pts = read_points(d / "points")
    tri, poly = read_faces(d / "faces")
    own = read_labels(d / "owner")
    nei = read_labels(d / "neighbour")
    nc = int(max(own.max(), nei.max() if len(nei) else -1)) + 1
    return {"points": pts, "faces": tri, "poly_faces": poly, "owner": own, "neighbour": nei,
            "patches": read_boundary(d / "boundary"), "n_cells": nc}


def _parse_values(s: str, ncomp: int):
    s = s.strip()
    m = re.match(r"uniform\s+(.*)", s, re.S)
    if m:
        v = np.array(m.group(1).replace("(", " ").replace(")", " ").split(), float)
        return ("uniform", v)
    m = re.match(r"nonuniform\s+List<\w+>", s)
    if m:
        body, n, _ = _read_list_block(s, m.end())
        v = np.array(body.replace("(", " ").replace(")", " ").split(), float)
        return ("list", v.reshape(n, ncomp) if ncomp > 1 else v)
    return None


def read_field(path, n_cells: int, patches: list) -> dict:
    """Returns {"internal": (n,) or (n,3), "patches": {name: array}} (cell/face values)."""
    raw = read_text(path)
    cm = re.search(r"class\s+(\w+);", raw[:1500])
    cls = cm.group(1) if cm else "volScalarField"
    ncomp = 3 if "Vector" in cls else 1
    text = _strip_header(raw)

    def expand(val, n):
        if val is None:
            return None
        kind, v = val
        if kind == "uniform":
            return np.tile(v, (n, 1)) if ncomp > 1 else np.full(n, v[0])
        return v

    m = re.search(r"internalField\s+(.*?);\s*\n\s*boundaryField", text, re.S)
    internal = expand(_parse_values(m.group(1), ncomp), n_cells) if m else None
    out = {"internal": internal, "patches": {}, "ncomp": ncomp, "class": cls}
    bf = text[text.find("boundaryField"):]
    for p in patches:
        pm = re.search(r"\b" + re.escape(p["name"]) + r"\s*\{(.*?)\n\s*\}", bf, re.S)
        if not pm:
            continue
        vm = re.search(r"\bvalue\s+(.*?);\s*$", pm.group(1), re.S | re.M)
        if vm:
            vals = expand(_parse_values(vm.group(1), ncomp), p["nFaces"])
            if vals is not None and len(vals) == p["nFaces"]:
                out["patches"][p["name"]] = vals
    return out
