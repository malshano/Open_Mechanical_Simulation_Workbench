def tet_mesh_to_polymesh(nodes, tets, tris, tri_patch, patch_names, patch_types,
                         cell_zone_ids=None, zone_names=None):
    """Convert a tetrahedral mesh to polyMesh arrays.

    tri_patch : patch index for each boundary triangle (-1 = not a boundary, e.g. internal interface)
    Returns dict with faces (F,3), owner, neighbour, patches [(name,type,start,n)], zones.
    """
    nodes = np.asarray(nodes, float)
    tets = np.asarray(tets, np.int64)
    M = len(tets)
    loc = np.array([[1, 2, 3], [0, 3, 2], [0, 1, 3], [0, 2, 1]])
    F = tets[:, loc].reshape(-1, 3)
    cell = np.repeat(np.arange(M), 4)
    key = np.sort(F, axis=1)
    uniq, inv, counts = np.unique(key, axis=0, return_inverse=True, return_counts=True)
    inv = inv.ravel()
    if counts.max() > 2:
        raise ValueError("Non-manifold mesh: a face is shared by more than two cells")

    order = np.argsort(inv, kind="stable")
    inv_s = inv[order]
    first = np.ones(len(order), bool)
    first[1:] = inv_s[1:] != inv_s[:-1]
    idx_first = order[first]  # one representative of every unique face
    c_first = cell[idx_first]
    is_int = counts == 2
    # second occurrence for internal faces
    second_mask = ~first
    idx_second = order[second_mask]
    uid_second = inv_s[second_mask]
    c_second = np.full(len(uniq), -1)
    c_second[uid_second] = cell[idx_second]

    own = c_first.copy()
    nei = c_second.copy()
    face_nodes = F[idx_first].copy()
    swap = is_int & (nei < own)
    own[swap], nei[swap] = nei[swap], own[swap].copy()

    # orientation: normal from owner to neighbour (or outward)
    cc = nodes[tets].mean(1)
    p0, p1, p2 = nodes[face_nodes[:, 0]], nodes[face_nodes[:, 1]], nodes[face_nodes[:, 2]]
    nrm = np.cross(p1 - p0, p2 - p0)
    fc = (p0 + p1 + p2) / 3
    flip = np.einsum("ij,ij->i", nrm, fc - cc[own]) < 0
    face_nodes[flip] = face_nodes[flip][:, [0, 2, 1]]

    # boundary patch assignment by matching to surface triangles
    bpatch = np.full(len(uniq), -1)
    if len(tris):
        tkey = np.sort(np.asarray(tris, np.int64), axis=1)
        allk = np.vstack([uniq, tkey])
        _, ainv = np.unique(allk, axis=0, return_inverse=True)
        ainv = ainv.ravel()
        uid_of = -np.ones(ainv.max() + 1, np.int64)
        uid_of[ainv[: len(uniq)]] = np.arange(len(uniq))
        hit = uid_of[ainv[len(uniq):]]
        ok = hit >= 0
        bpatch[hit[ok]] = np.asarray(tri_patch)[ok]

    bnd = ~is_int
    unassigned = bnd & (bpatch < 0)
    patch_names = list(patch_names)
    patch_types = list(patch_types)
    if unassigned.any():
        if "defaultFaces" not in patch_names:
            patch_names.append("defaultFaces")
            patch_types.append("wall")
        bpatch[unassigned] = patch_names.index("defaultFaces")

    int_idx = np.where(is_int)[0]
    int_idx = int_idx[np.lexsort((nei[int_idx], own[int_idx]))]
    bnd_idx = np.where(bnd)[0]
    bnd_idx = bnd_idx[np.lexsort((own[bnd_idx], bpatch[bnd_idx]))]

    faces_out = np.vstack([face_nodes[int_idx], face_nodes[bnd_idx]])
    owner_out = np.concatenate([own[int_idx], own[bnd_idx]])
    neigh_out = nei[int_idx]
    patches = []
    start = len(int_idx)
    bp_sorted = bpatch[bnd_idx]
    for i, (nm, tp) in enumerate(zip(patch_names, patch_types)):
        n = int((bp_sorted == i).sum())
        patches.append({"name": nm, "type": tp, "start": start, "nFaces": n})
        start += n
    zones = []
    if cell_zone_ids is not None:
        cz = np.asarray(cell_zone_ids)
        for zi, zn in enumerate(zone_names):
            zones.append((zn, np.where(cz == zi)[0]))
    return {"points": nodes, "faces": faces_out, "owner": owner_out, "neighbour": neigh_out,
            "patches": patches, "cell_zones": zones, "n_cells": M}


def face_zone(pm: dict, tris, inside_cells) -> tuple:
    """Internal faces of pm matching the triangles `tris`, with the flip map that makes every face normal point out
    of the cell set `inside_cells` (bool per cell). Returns (face indices, flip)."""
    ni = len(pm["neighbour"])
    key = np.sort(np.asarray(pm["faces"][:ni], np.int64), axis=1)
    t = np.sort(np.asarray(tris, np.int64), axis=1)
    allk = np.vstack([key, t])
    _, inv = np.unique(allk, axis=0, return_inverse=True)
    inv = inv.ravel()
    face_of = -np.ones(inv.max() + 1, np.int64)
    face_of[inv[:ni]] = np.arange(ni)
    f = face_of[inv[ni:]]
    if (f < 0).any():
        raise ValueError(f"{int((f < 0).sum())} moving-zone faces are not internal mesh faces - regenerate the mesh")
    f = np.unique(f)
    own_in = np.asarray(inside_cells)[pm["owner"][f]]
    return f, ~own_in  # (owner inside: owner -> neighbour already points outwards)


def write_polymesh(mesh_dir: Path, pm: dict, extra_cell_zones=(), face_zones=()):
    mesh_dir = Path(mesh_dir)
    mesh_dir.mkdir(parents=True, exist_ok=True)
    pts, faces, own, nei = pm["points"], pm["faces"], pm["owner"], pm["neighbour"]
    note = (f'    note        "nPoints:{len(pts)}  nCells:{pm["n_cells"]}  nFaces:{len(faces)}  '
            f'nInternalFaces:{len(nei)}";\n')

    def write(name, cls, body):
        hdr = header(cls, name, "constant/polyMesh")
        if name in ("owner", "neighbour"):
            hdr = hdr.replace("    location", note + "    location")
        (mesh_dir / name).write_text(hdr + body + "\n", newline="\n")

    b = io.StringIO()
    b.write(f"{len(pts)}\n(\n")
    np.savetxt(b, pts, fmt="(%.9g %.9g %.9g)")
    b.write(")\n")
    write("points", "vectorField", b.getvalue())

    b = io.StringIO()
    b.write(f"{len(faces)}\n(\n")
    np.savetxt(b, faces, fmt="3(%d %d %d)")
    b.write(")\n")
    write("faces", "faceList", b.getvalue())

    for nm, arr in (("owner", own), ("neighbour", nei)):
        b = io.StringIO()
        b.write(f"{len(arr)}\n(\n")
        np.savetxt(b, arr, fmt="%d")
        b.write(")\n")
        write(nm, "labelList", b.getvalue())

    b = io.StringIO()
    b.write(f"{len(pm['patches'])}\n(\n")
    for p in pm["patches"]:
        b.write(f"    {p['name']}\n    {{\n        type            {p['type']};\n")
        if p["type"] == "wall":
            b.write("        inGroups        List<word> 1(wall);\n")
        b.write(f"        nFaces          {p['nFaces']};\n        startFace       {p['start']};\n    }}\n")
    b.write(")\n")
    write("boundary", "polyBoundaryMesh", b.getvalue())

    zones = list(pm.get("cell_zones", [])) + list(extra_cell_zones)
    if zones:
        b = io.StringIO()
        b.write(f"{len(zones)}\n(\n")
        for zn, cells in zones:
            b.write(f"{zn}\n{{\n    type cellZone;\ncellLabels      List<label> {len(cells)}\n(\n")
            np.savetxt(b, cells, fmt="%d")
            b.write(")\n;\n}\n")
        b.write(")\n")
        write("cellZones", "regIOobject", b.getvalue())
    else:
        z = mesh_dir / "cellZones"
        if z.exists():
            z.unlink()
    if face_zones:
        b = io.StringIO()
        b.write(f"{len(face_zones)}\n(\n")
        for zn, fidx, flip in face_zones:
            b.write(f"{zn}\n{{\n    type faceZone;\nfaceLabels      List<label> {len(fidx)}\n(\n")
            np.savetxt(b, fidx, fmt="%d")
            b.write(f")\n;\nflipMap         List<bool> {len(flip)}\n(\n")
            np.savetxt(b, np.asarray(flip, int), fmt="%d")
            b.write(")\n;\n}\n")
        b.write(")\n")
        write("faceZones", "regIOobject", b.getvalue())


def polymesh_quality(pm: dict) -> dict:
    """OpenFOAM-style quality metrics (non-orthogonality, skewness) for a tet polyMesh."""
    pts, faces, own, nei = pm["points"], pm["faces"], pm["owner"], pm["neighbour"]
    nc = pm["n_cells"]
    fc = pts[faces].mean(1)
    sf = 0.5 * np.cross(pts[faces[:, 1]] - pts[faces[:, 0]], pts[faces[:, 2]] - pts[faces[:, 0]])
    # cell centres for tets = vertex average (exact for tets)
    cc = np.zeros((nc, 3))
    cnt = np.zeros(nc)
    # each tet has 4 faces x 3 nodes -> average of face centres equals vertex average
    np.add.at(cc, own, fc)
    np.add.at(cnt, own, 1)
    np.add.at(cc, nei, fc[: len(nei)])
    np.add.at(cnt, nei, 1)
    cc /= cnt[:, None]
    ni = len(nei)
    d = cc[nei] - cc[own[:ni]]
    s = sf[:ni]
    cosang = np.einsum("ij,ij->i", d, s) / (np.linalg.norm(d, axis=1) * np.linalg.norm(s, axis=1) + 1e-300)
    nonortho = np.degrees(np.arccos(np.clip(cosang, -1, 1)))
    # skewness: distance from face centre to the d-line intersection, relative to |d|
    dn = d / (np.linalg.norm(d, axis=1)[:, None] + 1e-300)
    t = np.einsum("ij,ij->i", fc[:ni] - cc[own[:ni]], s) / (np.einsum("ij,ij->i", dn, s) + 1e-300)
    xi = cc[own[:ni]] + dn * t[:, None]
    skew = np.linalg.norm(fc[:ni] - xi, axis=1) / (np.linalg.norm(d, axis=1) + 1e-300)
    return {
        "non_orthogonality_max": float(nonortho.max()) if ni else 0.0,
        "non_orthogonality_mean": float(nonortho.mean()) if ni else 0.0,
        "n_non_ortho_gt70": int((nonortho > 70).sum()),
        "skewness_max": float(skew.max()) if ni else 0.0,
        "n_skew_gt4": int((skew > 4).sum()),
    }


